-- =============================================================================
-- NUVORA 2.0  |  20261011090300  |  Orders and order lines
--
-- Wallet-free by construction: an order is a statement of what is being bought and
-- what the gateway must collect for it. There is no balance column anywhere in this
-- schema, because NUVORA never holds customer money.
--
-- WRITES ARE SERVER-ONLY. No RLS policy in 20261011090600 grants INSERT, UPDATE or
-- DELETE to anon or authenticated on either table. RLS cannot validate a price, so a
-- client that can write an order can write its own discount. Orders are created and
-- mutated exclusively by server routes holding the service-role key, after the
-- pricing engine has recomputed every figure from the database.
-- =============================================================================

-- Human-readable, monotonically increasing reference. Generated by sequence rather
-- than at random so support can reason about ordering and so collisions are
-- impossible by construction.
create sequence if not exists public.order_number_seq start 1000;

create or replace function public.generate_order_number()
returns text
language plpgsql
volatile
as $$
declare
  v_seq bigint;
begin
  v_seq := nextval('public.order_number_seq');
  return 'NUV-'
         || to_char(now() at time zone 'utc', 'YYYYMMDD')
         || '-'
         || lpad(v_seq::text, 6, '0');
end;
$$;

comment on function public.generate_order_number() is
  'Returns NUV-YYYYMMDD-NNNNNN. Sequence-backed, so it cannot collide.';

grant execute on function public.generate_order_number() to service_role;

-- -----------------------------------------------------------------------------
-- orders
-- -----------------------------------------------------------------------------
create table public.orders (
  id                    uuid primary key default gen_random_uuid(),
  order_number          text not null unique default public.generate_order_number(),

  -- Nullable: a customer may check out as a guest without an account. When they do
  -- sign in later, the order is claimed by email rather than by rewriting history.
  user_id               uuid,
  email                 citext not null,
  billing_country       text,

  status                public.order_status not null default 'pending_payment',
  currency              text not null,

  -- Recomputable breakdown. total_minor is what the gateway is asked to collect.
  subtotal_minor        bigint not null,
  discount_minor        bigint not null default 0,
  tax_minor             bigint not null default 0,
  total_minor           bigint not null,

  -- Client-supplied key that makes order creation safe to retry: a double-submitted
  -- checkout resolves to the existing order instead of charging twice.
  idempotency_key       text not null,

  -- Which version of the pricing engine produced these figures.
  engine_version        text not null,

  internal_note         text,           -- staff only, never returned to a buyer
  created_ip_hash       text,           -- salted hash, never a raw IP address

  paid_at               timestamptz,
  fulfilled_at          timestamptz,
  cancelled_at          timestamptz,
  refunded_at           timestamptz,

  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),

  constraint orders_currency_format       check (currency ~ '^[A-Z]{3}$'),
  constraint orders_billing_country_format check (
    billing_country is null or billing_country ~ '^[A-Z]{2}$'
  ),
  constraint orders_amounts_non_negative check (
    subtotal_minor >= 0 and discount_minor >= 0 and tax_minor >= 0 and total_minor >= 0
  ),
  constraint orders_discount_within_subtotal check (discount_minor <= subtotal_minor),
  -- The stored total must be exactly what the parts add up to. A mismatch here would
  -- mean we charged a figure nobody can reconstruct.
  constraint orders_total_consistent
    check (total_minor = subtotal_minor - discount_minor + tax_minor),
  constraint orders_idempotency_key_present check (length(idempotency_key) between 8 and 200)
);

comment on table public.orders is
  'One purchase. Paid in full at checkout through the gateway; NUVORA stores no balance.';
comment on column public.orders.email is
  'Needed for delivery and receipts. The only personal data an order requires.';
comment on column public.orders.created_ip_hash is
  'Salted hash for fraud review. A raw IP address is never stored.';

create unique index orders_idempotency_key_idx on public.orders (idempotency_key);
create index orders_user_idx          on public.orders (user_id, created_at desc);
create index orders_email_idx         on public.orders (email, created_at desc);
create index orders_status_idx        on public.orders (status, created_at desc);

create trigger orders_touch_updated_at
  before update on public.orders
  for each row execute function public.touch_updated_at();

-- -----------------------------------------------------------------------------
-- order_items
--
-- Every figure that was used to price the line is copied onto the line: unit price,
-- unit cost and the price row consulted. A later change to the catalogue must never
-- alter what a historic order says it cost. Product name and line are snapshotted
-- for the same reason.
-- -----------------------------------------------------------------------------
create table public.order_items (
  id                  uuid primary key default gen_random_uuid(),
  order_id            uuid not null references public.orders(id) on delete cascade,

  -- RESTRICT, not CASCADE: deleting a product must never quietly delete order lines
  -- and the revenue record they represent.
  product_id          uuid not null references public.products(id) on delete restrict,
  price_id            uuid references public.product_prices(id) on delete restrict,

  -- Snapshot, so the receipt still reads correctly after a rename.
  product_name        text not null,
  product_line        public.product_line not null,
  product_attributes  jsonb not null default '{}'::jsonb,

  unit_price_minor    bigint not null,   -- charged to the customer
  unit_cost_minor     bigint not null,   -- HIDDEN: our cost at the time of sale
  quantity            integer not null,
  line_total_minor    bigint not null,

  fulfilment_status   public.fulfilment_status not null default 'pending',
  -- Customer-facing deliverable: the voucher code, the eSIM QR, the activation link.
  delivery_payload    jsonb,
  delivered_at        timestamptz,
  -- Internal supplier handle. Never returned to a buyer.
  supplier_reference  text,
  fulfilment_error    text,

  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),

  constraint order_items_quantity_sane   check (quantity > 0 and quantity <= 100),
  constraint order_items_price_non_negative check (unit_price_minor >= 0),
  constraint order_items_cost_non_negative  check (unit_cost_minor >= 0),
  -- Line total must equal the arithmetic; the server computes it, the database checks it.
  constraint order_items_total_consistent
    check (line_total_minor = unit_price_minor * quantity),
  -- Margin guard rail: an order line may never be sold below the cost recorded on it.
  constraint order_items_never_below_cost check (unit_cost_minor <= unit_price_minor),
  constraint order_items_delivered_iff_payload check (
    fulfilment_status <> 'completed' or delivery_payload is not null
  )
);

comment on table public.order_items is
  'One line of an order, with a full price/cost snapshot so history cannot be rewritten.';
comment on column public.order_items.unit_cost_minor is
  'HIDDEN FROM BUYERS. Our cost per unit at the time of sale, kept for margin reporting.';
comment on column public.order_items.delivery_payload is
  'Customer-facing deliverable only. Supplier secrets and raw API responses never go here.';

create index order_items_order_idx   on public.order_items (order_id);
create index order_items_product_idx on public.order_items (product_id);
create index order_items_fulfilment_idx
  on public.order_items (fulfilment_status, created_at)
  where fulfilment_status in ('pending', 'submitted');

create trigger order_items_touch_updated_at
  before update on public.order_items
  for each row execute function public.touch_updated_at();
