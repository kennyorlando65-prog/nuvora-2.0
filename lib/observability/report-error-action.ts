"use server";

import { reportError } from "@/lib/observability/report-error";

/**
 * Reports a client-side render error to the server and returns its correlation id.
 *
 * WHY A SERVER ACTION AND NOT A CONSOLE LOG. A browser-side `console.error` is invisible to
 * whoever operates the deployment - it lives in the customer's browser, not in the logs. The
 * brief was explicit: log the full error server-side with a correlation id, and show that id
 * on the page. This is the bridge that makes that true for an error raised during rendering,
 * which by definition happened in the browser.
 *
 * The browser sends only a message and a stack. No cookie, no token, no form value and no
 * customer data is accepted or forwarded, and the server redacts the payload before logging
 * it anyway - so a crafted input cannot use this route to write a key into the logs.
 */
export async function reportClientError(input: {
  message: string;
  stack?: string;
  context: string;
}): Promise<{ correlationId: string }> {
  const error = new Error(
    typeof input.message === "string" && input.message ? input.message.slice(0, 2000) : "Client render error.",
  );

  // The browser's stack is more useful than the one generated by constructing an Error here,
  // because it names the component that failed.
  if (typeof input.stack === "string" && input.stack) {
    error.stack = input.stack.slice(0, 8000);
  }

  const context =
    typeof input.context === "string" && input.context ? input.context.slice(0, 200) : "client";

  const reported = reportError(error, context);

  return { correlationId: reported.correlationId };
}
